"""Generate target views with (dated) SEVA for one sample, using SEVA's own sampler.

Inputs are in the dataset's format (``timemachine.data.dataset``): views ordered
inputs first, images in [-1, 1], normalized intrinsics, camera-to-world poses.
All views must fit in one forward pass (no two-pass procedural sampling): fine
for our 8-view samples.
"""
from __future__ import annotations

from contextlib import nullcontext

import torch
from seva.eval import create_samplers, do_sample, get_value_dict

from timemachine.model.dated_seva import DatedSGMWrapper
from timemachine.model.loading import SevaComponents

LATENT_CHANNELS = 4
DOWNSAMPLE = 8


@torch.no_grad()
def generate_targets(
    components: SevaComponents,
    images: torch.Tensor,          # (V, 3, H, W) in [-1, 1]; targets' pixels are ignored
    K: torch.Tensor,               # (V, 3, 3) normalized intrinsics
    c2w: torch.Tensor,             # (V, 4, 4)
    is_input: torch.Tensor,        # (V,) bool, inputs first
    dates: torch.Tensor | None = None,       # (V,) decimal years (dated model only)
    date_valid: torch.Tensor | None = None,  # (V,) bool
    cfg: float = 2.0, cfg_min: float = 1.2, num_steps: int = 50,
    camera_scale: float = 2.0, seed: int = 0,
) -> torch.Tensor:
    """All V frames as generated by SEVA, (V, 3, H, W) in [-1, 1].

    Input frames are reproduced from their latents; target frames are generated.
    Settings follow SEVA's demo defaults (Euler, 50 steps, multiview CFG 2.0).
    """
    n_inputs = int(is_input.sum())
    if not bool(is_input[:n_inputs].all()):
        raise ValueError("Views must be ordered inputs first (SEVA's convention).")
    T, _, H, W = images.shape
    value_dict = get_value_dict(
        curr_imgs=images.float().cpu(),
        curr_input_frame_indices=list(range(n_inputs)),
        curr_c2ws=c2w.float().cpu(),
        curr_Ks=K.float().cpu(),
        curr_input_camera_indices=list(range(n_inputs)),
        all_c2ws=c2w.float().cpu(),
        camera_scale=camera_scale,
    )
    sampler = create_samplers(guider_types=1, discretization=components.denoiser.discretization,
                              num_frames=[T], num_steps=num_steps, cfg_min=cfg_min)[0]
    model = components.model
    if dates is not None and not isinstance(model, DatedSGMWrapper):
        raise ValueError("Dates given, but the model has no date module (load with dated=True).")
    context = model.dates(dates.cuda(), None if date_valid is None else date_valid.cuda()) \
        if dates is not None else nullcontext()

    torch.manual_seed(seed)
    with context:
        samples = do_sample(model, components.ae, components.conditioner, components.denoiser, sampler,
                            value_dict, H, W, LATENT_CHANNELS, DOWNSAMPLE, T, cfg, verbose=False)
    return samples.float().clamp(-1, 1)
