"""Generate target views with (dated) SEVA for one sample, using SEVA's own sampler.

Inputs are in the dataset's format (``timemachine.data.dataset``): views ordered
inputs first, images in [-1, 1], normalized intrinsics, camera-to-world poses.
All views must fit in one forward pass (no two-pass procedural sampling).

**Frames per forward pass.** SEVA's released weights were last trained at 21 frames,
and its own pipeline always runs 21: a smaller set is padded by repeating its last
frame (``seva.eval.pad_indices``, mode "last") and the padded outputs are dropped.
Sampling fewer frames unpadded gives fragmented, over-saturated renders ("abnormal
color overflows", SEVA paper App. D.3; reproduced on our data, docs/findings.md
2026-11-19). ``pad_to`` therefore defaults to 21; ``pad_to=None`` reproduces the
unpadded renders of runs before that date.
"""
from __future__ import annotations

from contextlib import nullcontext

import torch
from seva.eval import create_samplers, do_sample, get_value_dict

from timemachine.model.dated_seva import DatedSGMWrapper
from timemachine.model.loading import SevaComponents

LATENT_CHANNELS = 4
DOWNSAMPLE = 8
SEVA_FRAMES = 21        # SEVA's native context length (version 1.1)


def padded_indices(n_views: int, pad_to: int | None) -> list[int]:
    """Frame order of one forward pass: the views, then the last one repeated up to ``pad_to`` (SEVA's "last" padding)."""
    return list(range(n_views)) + [n_views - 1] * max(0, (pad_to or 0) - n_views)


@torch.no_grad()
def generate_targets(
    components: SevaComponents,
    images: torch.Tensor,          # (V, 3, H, W) in [-1, 1]; targets' pixels are ignored
    K: torch.Tensor,               # (V, 3, 3) normalized intrinsics
    c2w: torch.Tensor,             # (V, 4, 4)
    is_input: torch.Tensor,        # (V,) bool, inputs first
    dates: torch.Tensor | None = None,       # (V,) decimal years (dated model only)
    date_valid: torch.Tensor | None = None,  # (V,) bool
    cfg: float = 2.0, cfg_min: float = 1.2, num_steps: int = 50,
    camera_scale: float = 2.0, seed: int = 0, uncond_dates: str = "same",
    pad_to: int | None = SEVA_FRAMES,
) -> torch.Tensor:
    """All V frames as generated by SEVA, (V, 3, H, W) in [-1, 1].

    Input frames are reproduced from their latents; target frames are generated.
    Settings follow SEVA's demo defaults (Euler, 50 steps, multiview CFG 2.0, 21 frames
    per forward pass with "last" padding; see the module docstring for ``pad_to``).
    ``uncond_dates``: what the unconditional CFG branch sees ("same" dates, or "unknown";
    see :mod:`timemachine.model.dated_seva`).
    """
    n_inputs = int(is_input.sum())
    if not bool(is_input[:n_inputs].all()):
        raise ValueError("Views must be ordered inputs first (SEVA's convention).")
    V, _, H, W = images.shape
    if n_inputs == V and (pad_to or 0) > V:
        raise ValueError("Padding repeats the last view, which must be a target.")
    idx = torch.tensor(padded_indices(V, pad_to))
    T = len(idx)
    value_dict = get_value_dict(
        curr_imgs=images.float().cpu()[idx],
        curr_input_frame_indices=list(range(n_inputs)),
        curr_c2ws=c2w.float().cpu()[idx],
        curr_Ks=K.float().cpu()[idx],
        curr_input_camera_indices=list(range(n_inputs)),
        all_c2ws=c2w.float().cpu(),          # centre and scale from the real cameras only, as SEVA does
        camera_scale=camera_scale,
    )
    sampler = create_samplers(guider_types=1, discretization=components.denoiser.discretization,
                              num_frames=[T], num_steps=num_steps, cfg_min=cfg_min)[0]
    model = components.model
    if dates is not None and not isinstance(model, DatedSGMWrapper):
        raise ValueError("Dates given, but the model has no date module (load with dated=True).")
    if dates is not None:
        valid = torch.ones_like(dates, dtype=torch.bool) if date_valid is None else date_valid
        context = model.dates(dates.cpu()[idx].cuda(), valid.cpu()[idx].cuda(), uncond=uncond_dates)
    else:
        context = nullcontext()

    torch.manual_seed(seed)
    with context:
        samples = do_sample(model, components.ae, components.conditioner, components.denoiser, sampler,
                            value_dict, H, W, LATENT_CHANNELS, DOWNSAMPLE, T, cfg, verbose=False)
    return samples.float().clamp(-1, 1)[:V]
